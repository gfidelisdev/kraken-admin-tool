// ProvisionKeyRequest asks Kraken to configure key-based SSH access on a remote host,
// using a one-time login (user/password) that is never persisted.
type ProvisionKeyRequest struct {
	ServerHost   string `json:"server_host"`
	ServerPort   string `json:"server_port"`
	SSHUser      string `json:"ssh_user"`
	SSHPassword  string `json:"ssh_password"`
	SudoPassword string `json:"sudo_password,omitempty"`
	// PrivateKey allows reusing a key generated by a previous (sudo_required) attempt.
	PrivateKey string `json:"private_key,omitempty"`
}

// ProvisionStep describes one action performed (or attempted) on the remote host.
type ProvisionStep struct {
	Name    string `json:"name"`
	Status  string `json:"status"` // "ok" | "skipped" | "failed" | "sudo_required"
	Message string `json:"message,omitempty"`
}

// ProvisionKeyResult is returned to the client. PrivateKey is only ever sent back to the
// admin who requested the provisioning; it is not stored by the backend.
type ProvisionKeyResult struct {
	Success      bool            `json:"success"`
	Code         string          `json:"code,omitempty"` // "sudo_required" | "invalid_sudo_password" | "auth_failed" | ...
	Message      string          `json:"message"`
	Steps        []ProvisionStep `json:"steps"`
	PrivateKey   string          `json:"private_key,omitempty"`
	PublicKey    string          `json:"public_key,omitempty"`
	Fingerprint  string          `json:"host_key_fingerprint,omitempty"`
	SudoRequired bool            `json:"sudo_required,omitempty"`
}

const provisionKeyComment = "kraken-admin-tool"

var safeUserRe = regexp.MustCompile(`^[a-zA-Z0-9_][a-zA-Z0-9_.\-]*\$?$`)

// generateProvisionKey creates a fresh ed25519 key pair; returns PEM private key and authorized_keys line.
func generateProvisionKey() (privatePEM string, authorizedLine string, err error) {
	pub, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		return "", "", err
	}
	block, err := ssh.MarshalPrivateKey(priv, provisionKeyComment)
	if err != nil {
		return "", "", err
	}
	sshPub, err := ssh.NewPublicKey(pub)
	if err != nil {
		return "", "", err
	}
	line := strings.TrimSpace(string(ssh.MarshalAuthorizedKey(sshPub))) + " " + provisionKeyComment
	return string(pem.EncodeToMemory(block)), line, nil
}

// authorizedKeyFromPrivate derives the authorized_keys line from an existing private key.
func authorizedKeyFromPrivate(privatePEM string) (string, ssh.Signer, error) {
	signer, err := ssh.ParsePrivateKey([]byte(privatePEM))
	if err != nil {
		return "", nil, err
	}
	line := strings.TrimSpace(string(ssh.MarshalAuthorizedKey(signer.PublicKey()))) + " " + provisionKeyComment
	return line, signer, nil
}

// installKeyCommand builds an idempotent shell snippet that adds the key to ~/.ssh/authorized_keys.
func installKeyCommand(authorizedLine string) string {
	q := quoteShell(authorizedLine)
	return "umask 077; mkdir -p \"$HOME/.ssh\" && touch \"$HOME/.ssh/authorized_keys\" && " +
		"(grep -qxF " + q + " \"$HOME/.ssh/authorized_keys\" || printf '%s\\n' " + q + " >> \"$HOME/.ssh/authorized_keys\") && " +
		"chmod 700 \"$HOME/.ssh\" && chmod 600 \"$HOME/.ssh/authorized_keys\" && " +
		"(command -v restorecon >/dev/null 2>&1 && restorecon -R \"$HOME/.ssh\" >/dev/null 2>&1 || true)"
}

// enablePubkeyCommand makes sure sshd accepts public key authentication and reloads it.
const enablePubkeyCommand = `set -e
CFG=/etc/ssh/sshd_config
cp -n "$CFG" "$CFG.kraken.bak" 2>/dev/null || true
if grep -qiE '^[[:space:]]*PubkeyAuthentication[[:space:]]+no' "$CFG"; then
  sed -i -E 's/^[[:space:]]*PubkeyAuthentication[[:space:]]+no/PubkeyAuthentication yes/I' "$CFG"
elif ! grep -qiE '^[[:space:]]*PubkeyAuthentication' "$CFG"; then
  echo 'PubkeyAuthentication yes' >> "$CFG"
fi
for f in /etc/ssh/sshd_config.d/*.conf; do
  [ -f "$f" ] && sed -i -E 's/^[[:space:]]*PubkeyAuthentication[[:space:]]+no/PubkeyAuthentication yes/I' "$f" || true
done
(sshd -t 2>/dev/null || /usr/sbin/sshd -t)
(systemctl reload sshd 2>/dev/null || systemctl reload ssh 2>/dev/null || service sshd reload 2>/dev/null || service ssh reload)`

func dialProvisionSSH(ctx context.Context, host, port, user string, auth []ssh.AuthMethod, fp *string) (*ssh.Client, error) {
	cfg := &ssh.ClientConfig{
		User: user,
		Auth: auth,
		HostKeyCallback: func(_ string, _ net.Addr, key ssh.PublicKey) error {
			if fp != nil {
				*fp = ssh.FingerprintSHA256(key)
			}
			return nil
		},
		Timeout: 10 * time.Second,
	}
	d := net.Dialer{Timeout: 10 * time.Second}
	conn, err := d.DialContext(ctx, "tcp", net.JoinHostPort(host, port))
	if err != nil {
		return nil, fmt.Errorf("could not reach %s:%s: %w", host, port, err)
	}
	c, chans, reqs, err := ssh.NewClientConn(conn, net.JoinHostPort(host, port), cfg)
	if err != nil {
		_ = conn.Close()
		return nil, err
	}
	return ssh.NewClient(c, chans, reqs), nil
}

func isAuthError(err error) bool {
	if err == nil {
		return false
	}
	s := strings.ToLower(err.Error())
	return strings.Contains(s, "unable to authenticate") || strings.Contains(s, "permission denied")
}

// ProvisionKeyAccess performs the whole remote setup. It never persists any credential.
func ProvisionKeyAccess(ctx context.Context, req ProvisionKeyRequest) *ProvisionKeyResult {
	res := &ProvisionKeyResult{Steps: []ProvisionStep{}}
	addStep := func(name, status, msg string) {
		res.Steps = append(res.Steps, ProvisionStep{Name: name, Status: status, Message: msg})
	}
	fail := func(code, msg string) *ProvisionKeyResult {
		res.Success = false
		res.Code = code
		res.Message = msg
		return res
	}

	host := strings.TrimSpace(req.ServerHost)
	port := strings.TrimSpace(req.ServerPort)
	if port == "" {
		port = "22"
	}
	user := strings.TrimSpace(req.SSHUser)
	if host == "" || user == "" || req.SSHPassword == "" {
		return fail("invalid_request", "Host, user and password are required to configure key access.")
	}
	if !safeUserRe.MatchString(user) {
		return fail("invalid_request", "Invalid SSH user name.")
	}

	// 1. Key material
	var authorizedLine string
	var signer ssh.Signer
	if strings.TrimSpace(req.PrivateKey) != "" {
		line, s, err := authorizedKeyFromPrivate(req.PrivateKey)
		if err != nil {
			return fail("invalid_request", "Provided private key is invalid.")
		}
		authorizedLine, signer = line, s
		res.PrivateKey = req.PrivateKey
	} else {
		privPEM, line, err := generateProvisionKey()
		if err != nil {
			return fail("internal", "Failed to generate key pair: "+err.Error())
		}
		s, err := ssh.ParsePrivateKey([]byte(privPEM))
		if err != nil {
			return fail("internal", "Failed to load generated key: "+err.Error())
		}
		authorizedLine, signer = line, s
		res.PrivateKey = privPEM
	}
	res.PublicKey = authorizedLine
	addStep("Generate key pair (ed25519)", "ok", "")

	// 2. Password login
	passwordAuth := []ssh.AuthMethod{
		ssh.Password(req.SSHPassword),
		ssh.KeyboardInteractive(func(_, _ string, questions []string, _ []bool) ([]string, error) {
			answers := make([]string, len(questions))
			for i := range answers {
				answers[i] = req.SSHPassword
			}
			return answers, nil
		}),
	}
	var fingerprint string
	pwClient, err := dialProvisionSSH(ctx, host, port, user, passwordAuth, &fingerprint)
	if err != nil {
		addStep("Connect with user/password", "failed", err.Error())
		res.PrivateKey, res.PublicKey = "", ""
		if isAuthError(err) {
			return fail("auth_failed", "Authentication failed: wrong user or password.")
		}
		return fail("connect_failed", err.Error())
	}
	defer pwClient.Close()
	res.Fingerprint = fingerprint
	addStep("Connect with user/password", "ok", "Host key "+fingerprint)

	pwExec := NewSSHExecutor(pwClient)
	isRoot := strings.EqualFold(user, "root")

	// 3. Install the public key
	if _, stderr, code, err := pwExec.Execute(ctx, installKeyCommand(authorizedLine)); err != nil || code != 0 {
		msg := strings.TrimSpace(stderr)
		if msg == "" && err != nil {
			msg = err.Error()
		}
		addStep("Install public key in ~/.ssh/authorized_keys", "failed", msg)
		return fail("install_failed", "Could not install the public key: "+msg)
	}
	addStep("Install public key in ~/.ssh/authorized_keys", "ok", "")

	// sudo helper: validates need + password
	runSudo := func(stepName, reason, cmd string) *ProvisionKeyResult {
		if !isRoot && req.SudoPassword == "" {
			addStep(stepName, "sudo_required", reason)
			res.SudoRequired = true
			return fail("sudo_required", "sudo password required: "+reason)
		}
		_, stderr, code, err := pwExec.ExecuteSudo(ctx, cmd, req.SudoPassword)
		if errors.Is(err, ErrInvalidSudoPassword) {
			addStep(stepName, "failed", "Invalid sudo password")
			res.SudoRequired = true
			return fail("invalid_sudo_password", "The sudo password is incorrect.")
		}
		if err != nil || code != 0 {
			msg := strings.TrimSpace(stderr)
			if msg == "" && err != nil {
				msg = err.Error()
			}
			addStep(stepName, "failed", msg)
			return fail("sudo_command_failed", stepName+" failed: "+msg)
		}
		addStep(stepName, "ok", "")
		return nil
	}

	keyAuth := []ssh.AuthMethod{ssh.PublicKeys(signer)}
	testKeyLogin := func() (*ssh.Client, error) {
		return dialProvisionSSH(ctx, host, port, user, keyAuth, nil)
	}

	// 4. Verify key login; if the server refuses, enable PubkeyAuthentication with sudo
	keyClient, err := testKeyLogin()
	if err != nil {
		addStep("Verify login with key", "failed", "Server refused the key: "+err.Error())
		if r := runSudo("Enable PubkeyAuthentication in sshd", "sshd does not accept public key authentication", enablePubkeyCommand); r != nil {
			return r
		}
		time.Sleep(500 * time.Millisecond)
		keyClient, err = testKeyLogin()
		if err != nil {
			addStep("Verify login with key (retry)", "failed", err.Error())
			return fail("key_login_failed", "Key login still fails after configuration: "+err.Error())
		}
	}
	defer keyClient.Close()
	addStep("Verify login with key", "ok", "")

	// 5. Docker access for this user
	keyExec := NewSSHExecutor(keyClient)
	out, stderr, code, _ := keyExec.Execute(ctx, "PATH=$PATH:/usr/local/bin:/usr/bin:/bin:/snap/bin docker info --format '{{.ServerVersion}}'")
	switch {
	case code == 0:
		addStep("Check Docker access", "ok", "Docker "+strings.TrimSpace(out))
	case strings.Contains(strings.ToLower(stderr), "permission denied"):
		if r := runSudo("Add user to the docker group", "user has no permission to use the Docker socket",
			fmt.Sprintf("usermod -aG docker %s 2>/dev/null || gpasswd -a %s docker", user, user)); r != nil {
			return r
		}
		addStep("Check Docker access", "ok", "User added to docker group (applies to new sessions)")
	case strings.Contains(strings.ToLower(stderr), "not found"):
		addStep("Check Docker access", "skipped", "Docker is not installed on the host (SSH access is ready)")
	default:
		addStep("Check Docker access", "skipped", strings.TrimSpace(stderr))
	}

	res.Success = true
	res.Message = "Key-based access configured successfully."
	return res
}

// ProvisionKeyHandler handles POST /api/hosts/provision-key (admin only).
func (h *Handler) ProvisionKeyHandler(w http.ResponseWriter, r *http.Request) {
	var req ProvisionKeyRequest
	w.Header().Set("Content-Type", "application/json")
	if err := json.NewDecoder(http.MaxBytesReader(w, r.Body, 1<<20)).Decode(&req); err != nil {
		w.WriteHeader(http.StatusBadRequest)
		_ = json.NewEncoder(w).Encode(map[string]string{"error": "Invalid request payload"})
		return
	}

	ctx, cancel := context.WithTimeout(r.Context(), 60*time.Second)
	defer cancel()
	res := ProvisionKeyAccess(ctx, req)

	username, userID := "system", uint(0)
	if u := auth.GetUserFromContext(r.Context()); u != nil {
		username, userID = u.Username, u.UserID
	}
	target := strings.TrimSpace(req.SSHUser) + "@" + strings.TrimSpace(req.ServerHost)
	status := "SUCCESS"
	if !res.Success {
		status = "FAILED"
	}
	if !res.Success && !res.SudoRequired {
		res.PrivateKey, res.PublicKey = "", ""
	}
	audit.Log(h.DB, userID, username, "PROVISION_SSH_KEY", "docker_server", target, res.Message, status)

	switch {
	case res.Success:
		w.WriteHeader(http.StatusOK)
	case res.Code == "sudo_required" || res.Code == "invalid_sudo_password":
		w.WriteHeader(http.StatusConflict)
	case res.Code == "auth_failed":
		w.WriteHeader(http.StatusUnauthorized)
	default:
		w.WriteHeader(http.StatusBadRequest)
	}
	_ = json.NewEncoder(w).Encode(res)
}
